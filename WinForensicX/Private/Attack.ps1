function Get-WfxAttackTechnique {
    <# Returns name/tactic/url for ATT&CK ids (unknown ids are returned with a blank name). #>
    param([string[]]$Id)
    foreach ($t in @($Id | Where-Object { $_ })) {
        $info = $script:WfxAttack[$t]
        $base = $t -replace '\.', '/'
        [pscustomobject]@{
            Id     = $t
            Name   = if ($info) { $info[0] } else { '' }
            Tactic = if ($info) { $info[1] } else { '' }
            Url    = "https://attack.mitre.org/techniques/$base/"
        }
    }
}
