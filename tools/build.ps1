<#
    Builds the single-file distributable: dist/WinForensicX.ps1
    - Concatenates Private → Analyzers → Collectors → Report → Public (same order as the module loader).
    - Embeds every Rules/*.json pack as a here-string so the single file needs no external assets.
    - Appends an entry point: run directly → interactive menu; dot-source → just loads the functions.
    - Writes one UTF-8 BOM at the top (so Windows PowerShell 5.1 reads the box-drawing characters correctly).
    Deterministic: files are processed in a fixed, sorted order so the output is byte-stable across builds.
#>
[CmdletBinding()]
param([string]$Root = (Split-Path -Parent $PSScriptRoot), [string]$OutFile)

$ErrorActionPreference = 'Stop'
$module = Join-Path $Root 'WinForensicX'
if (-not $OutFile) { $OutFile = Join-Path $Root 'dist/WinForensicX.ps1' }
$distDir = Split-Path -Parent $OutFile
if (-not (Test-Path $distDir)) { New-Item -ItemType Directory -Path $distDir -Force | Out-Null }

$version = (Import-PowerShellDataFile (Join-Path $module 'WinForensicX.psd1')).ModuleVersion

$sb = New-Object System.Text.StringBuilder
function Add-Line { param($t = '') [void]$sb.AppendLine($t) }

Add-Line "#requires -version 5.1"
Add-Line "<#"
Add-Line "    WinForensicX $version — single-file build (read-only DFIR triage for Windows)."
Add-Line "    Generated by tools/build.ps1. Do not edit by hand; edit the module and rebuild."
Add-Line ""
Add-Line "    Run directly for the interactive menu:   .\WinForensicX.ps1"
Add-Line "    Run a triage straight away:               .\WinForensicX.ps1 -RunTriage"
Add-Line "    Show help / commands / limitations:       .\WinForensicX.ps1 -Help"
Add-Line "    Load the functions into a session:        . .\WinForensicX.ps1   (then call Invoke-WfxTriage, etc.)"
Add-Line ""
Add-Line "    Defensive tool: credential exposure is audited and REDACTED (type + length only)."
Add-Line "    It never extracts, decrypts or dumps secrets, hashes, memory or credential stores."
Add-Line "#>"
Add-Line "param([switch]`$RunTriage, [switch]`$Menu, [switch]`$Help, [string]`$OutputPath = '', [switch]`$NoAuto)"
Add-Line ""

# ── Concatenate the source layers in load order ──
foreach ($layer in 'Private', 'Analyzers', 'Collectors', 'Report', 'Public') {
    $dir = Join-Path $module $layer
    if (-not (Test-Path $dir)) { continue }
    foreach ($file in Get-ChildItem -LiteralPath $dir -Filter *.ps1 | Sort-Object Name) {
        Add-Line "# ===== $layer/$($file.Name) ====="
        # Get-Content -Raw strips a leading BOM, so no stray U+FEFF lands mid-file.
        Add-Line (Get-Content -LiteralPath $file.FullName -Raw)
        Add-Line ''
    }
}

# ── Embed the rule packs (override the empty $script:WfxEmbeddedRules from Rules.ps1) ──
Add-Line "# ===== embedded rule packs ====="
Add-Line '$script:WfxEmbeddedRules = @{}'
foreach ($json in Get-ChildItem -LiteralPath (Join-Path $module 'Rules') -Filter *.json | Sort-Object Name) {
    $name = [IO.Path]::GetFileNameWithoutExtension($json.Name)
    $content = (Get-Content -LiteralPath $json.FullName -Raw).TrimEnd()
    if ($content -match "(?m)^'@") { throw "Rule pack $name contains a here-string terminator at line start; cannot embed safely." }
    Add-Line "`$script:WfxEmbeddedRules['$name'] = @'"
    Add-Line $content
    Add-Line "'@"
}
Add-Line ''

# ── Entry point ──
Add-Line "# ===== entry point ====="
Add-Line '$script:WfxSingleFile = $true'
Add-Line 'if (-not $NoAuto) {'
Add-Line '    if ($Help) { Show-WfxHelp -Html }'
Add-Line '    elseif ($RunTriage) { Invoke-WfxTriage -OutputPath $OutputPath }'
Add-Line '    elseif ($Menu) { Show-WfxMenu -OutputPath $OutputPath }'
Add-Line "    elseif (`$MyInvocation.InvocationName -ne '.') { Show-WfxMenu -OutputPath `$OutputPath }"
Add-Line '}'

# ── Write with a single UTF-8 BOM ──
$text = $sb.ToString() -replace "`r`n", "`n" -replace "`n", "`r`n"
[IO.File]::WriteAllText($OutFile, $text, (New-Object Text.UTF8Encoding($true)))

$bytes = (Get-Item $OutFile).Length
$sha = (Get-FileHash -LiteralPath $OutFile -Algorithm SHA256).Hash
Write-Host "Built $OutFile" -ForegroundColor Green
Write-Host ("  {0:N0} bytes   SHA-256 {1}" -f $bytes, $sha)
